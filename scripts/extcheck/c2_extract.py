r"""Check 2: build runs/<stamp>/gen_study.h from the study's own sources, so the harness reuses (not rewrites) the
study's generators and register layouts. Each item is cut out by name from src/study/arith_gpu.h (layouts, form and
slot helpers; its HIP part is not included) and src/study/arith_more.hip (problem generators for the 16-bit
accumulator, integer and sparse forms; the edge-case table and sweep). Nothing is edited except the wrapper text.

Usage: python3 c2_extract.py <study src dir> <out header>
"""
import re
import sys


def cut(lines, start_rx, end_rx=None):
    """Lines from the first line matching start_rx to the end of its braces (or up to, not including, end_rx)."""
    i0 = next(i for i, ln in enumerate(lines) if re.search(start_rx, ln))
    if end_rx:
        i1 = next(i for i in range(i0 + 1, len(lines)) if re.search(end_rx, lines[i]))
        return lines[i0:i1]
    depth, seen = 0, False
    out = []
    for ln in lines[i0:]:
        out.append(ln)
        code = re.sub(r'"[^"]*"', '""', ln.split("//")[0])
        depth += code.count("{") - code.count("}")
        seen = seen or "{" in code
        if seen and depth <= 0:
            break
    return out


def main():
    src, outp = sys.argv[1], sys.argv[2]
    gpu = open(f"{src}/arith_gpu.h").read().split("\n")
    more = open(f"{src}/arith_more.hip").read().split("\n")
    o = ["// generated by scripts/extcheck/c2_extract.py from src/study/arith_gpu.h and arith_more.hip; do not edit",
         '#include "arith_model.h"', '#include "arith_data.h"', "#include <cstdio>", "#include <cstring>",
         "#include <functional>", "#include <random>", "#include <string>", "#include <vector>",
         "static bool g_break = false;  // the study's own break switch; the harness leaves it false", "",
         "namespace arith {"]
    for rx in (r"^enum Form \{", r"^enum Mod \{", r"^inline int words_ab", r"^inline int elem_bits", r"^inline bool acc16",
               r"^struct Slot", r"^inline Slot slot_ab", r"^inline Slot slot_cd", r"^enum SForm", r"^inline int sdense",
               r"^inline int swords_b", r"^inline Slot sslot_b"):
        o += cut(gpu, rx) + [""]
    o.append("}  // namespace arith\n")
    for rx in (r"^static int in_form", r"^static ad::Problem make16", r"^static uint32_t conv16", r"^struct IProblem",
               r"^static int int_k", r"^static IProblem make_int", r"^static bool s_h", r"^struct SProblem",
               r"^static int s_in_form", r"^static uint32_t sparse_model", r"^static SProblem make_sparse",
               r"^static uint32_t bf16_of"):
        o += cut(more, rx) + [""]
    # the edge cases quoted in matrix-arithmetic.md, and the sweep of single BF16 products
    o.append("struct EdgeCase { const char * name; int form; uint32_t a[2], b[2], c, want; int slot; };")
    case_lines = cut(more, r"const Case cases\[\] = \{")
    o.append("static const EdgeCase edge_cases[] = {")
    o += case_lines[1:-1]
    o.append("};")
    sweep = cut(more, r"for \(int esum : \{-140", r"const std::vector<uint32_t> d = run_problems\(arith::BF16, ps\);")
    o.append("static std::vector<ad::Problem> edge_sweep() {\n    std::vector<ad::Problem> ps;")
    o += sweep
    o.append("    return ps;\n}")
    open(outp, "w").write("\n".join(o) + "\n")


if __name__ == "__main__":
    main()
