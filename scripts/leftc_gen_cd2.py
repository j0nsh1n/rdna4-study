#!/usr/bin/env python3
"""Generate src/study/left_cd2_blocks.h: the CD-2 variant of the fix round (test T4), timed by src/study/left_cvt.hip.

Usage: python3 scripts/leftc_gen_cd2.py > src/study/left_cd2_blocks.h

use_e_lds_ahead (scripts/cvt_gen_timing.py) splits a block of 8 words into two halves of 4 words; each half issues its
16 LDS loads and then waits until at most 16 are outstanding, so up to 32 loads are in flight at its wait. LD-2 found
that a wave issues LDS loads at one per cycle only while fewer than about 17 to 22 are waiting. use_e_lds_ahead8 keeps
the same instructions and registers (cvt_gen_timing.py's step list E, copied below) but splits the block into four
quarters of 2 words: each quarter issues its 8 loads, waits until at most 8 are outstanding (s_wait_dscnt 8: the
previous quarter's loads are back) and consumes the previous quarter. At most 16 loads are in flight.
Registers as in cvt_time_blocks.h (v64-v143, CVT_CLOBBERS).
"""

# cvt_gen_timing.py's (e): FP16 table in LDS (byte address 2 * code at LDS 0): pairs (b0, b1) in t2, (b2, b3) in t3
E = ["v_lshlrev_b32 v{t0}, 1, v{w}", "v_lshrrev_b32 v{t1}, 7, v{w}", "v_lshrrev_b32 v{u0}, 15, v{w}",
     "v_lshrrev_b32 v{u1}, 23, v{w}",
     "v_and_b32 v{t0}, 0x1fe, v{t0}", "v_and_b32 v{t1}, 0x1fe, v{t1}", "v_and_b32 v{u0}, 0x1fe, v{u0}",
     "v_and_b32 v{u1}, 0x1fe, v{u1}",
     "ds_load_u16_d16 v{t2}, v{t0}", "ds_load_u16_d16_hi v{t2}, v{t1}", "ds_load_u16_d16 v{t3}, v{u0}",
     "ds_load_u16_d16_hi v{t3}, v{u1}"]
CONS = ["v_dot2_f32_f16 v{a}, v{t2}, v137, v{a}", "v_dot2_f32_f16 v{a}, v{t3}, v137, v{a}"]


def regs(j):
    return dict(w=96 + j, t0=64 + 4 * j, t1=65 + 4 * j, t2=66 + 4 * j, t3=67 + 4 * j, u0=104 + 3 * j, u1=105 + 3 * j,
                u2=106 + 3 * j, a=128 + j)


lines = []
for q in range(4):
    me = range(2 * q, 2 * q + 2)
    prev = range(2 * ((q + 3) % 4), 2 * ((q + 3) % 4) + 2)
    for st in E:
        for j in me:
            lines.append(st.format(**regs(j)))
    lines.append("s_wait_dscnt 8")
    for st in CONS:
        for j in prev:
            lines.append(st.format(**regs(j)))

print("// Generated by scripts/leftc_gen_cd2.py; do not edit by hand.")
print("#pragma once")
print("#define CVT_BLOCK_use_e_lds_ahead8 \\")
print(" \\\n".join('    "%s\\n"' % ln for ln in lines))
